// Pure deterministic OHLCV generator so charts always end at exact current price
// and reflect timeframe returns cleanly.
// Known invariant check: generateCandleSeries('SPX', 6142.84, 0.78, '1D') always ends with close === 6142.84
// and high >= Math.max(open, close) && low <= Math.min(open, close) for all bars.
export function generateCandleSeries(
  symbol: string,
  currentPrice: number,
  dailyChangePct: number,
  timeframe: Timeframe
): { points: CandlePoint[]; periodChangePct: number } {
  const counts: Record<Timeframe, number> = {
    '1D': 48,
    '5D': 55,
    '1M': 60,
    '6M': 72,
    YTD: 76,
    '1Y': 84,
    '5Y': 96,
  };
  const count = counts[timeframe];

  let seed = 0;
  const key = `${symbol}:${timeframe}`;
  for (let i = 0; i < key.length; i++) {
    seed = (seed * 33 + key.charCodeAt(i)) >>> 0;
  }
  const nextRand = () => {
    seed = (seed * 1664525 + 1013904223) >>> 0;
    return seed / 4294967296;
  };

  // Scale expected total period drift from dailyChangePct + deterministic asset drift
  const tfMultiplier: Record<Timeframe, number> = {
    '1D': 1,
    '5D': 2.1,
    '1M': 3.8,
    '6M': 9.5,
    YTD: 11.2,
    '1Y': 14.5,
    '5Y': 36.0,
  };

  const driftBias = ((seed % 100) - 42) / 100;
  const rawPeriodPct =
    timeframe === '1D'
      ? dailyChangePct
      : Number(
          Math.max(
            -65,
            Math.min(180, dailyChangePct * tfMultiplier[timeframe] * 0.65 + driftBias * tfMultiplier[timeframe] * 1.4)
          ).toFixed(2)
        );

  const startPrice = currentPrice / (1 + rawPeriodPct / 100);
  const rawPath: number[] = [startPrice];
  const stepVol =
    timeframe === '1D'
      ? Math.max(0.0012, Math.abs(dailyChangePct) * 0.0022)
      : Math.max(0.006, 0.012 * Math.sqrt(tfMultiplier[timeframe] / 4));

  for (let i = 1; i < count; i++) {
    const prev = rawPath[i - 1];
    const shock = (nextRand() - 0.495) * 2 * stepVol;
    rawPath.push(Math.max(currentPrice * 0.15, prev * (1 + shock)));
  }

  // Bridge smoothly so final close equals exact currentPrice
  const terminalRaw = rawPath[count - 1];
  const points: CandlePoint[] = [];

  for (let i = 0; i < count; i++) {
    const t = i / (count - 1);
    const bridgedClose =
      i === count - 1
        ? currentPrice
        : rawPath[i] * Math.pow(currentPrice / terminalRaw, t);

    const open = i === 0 ? startPrice : points[i - 1].close;
    const wickSpan = Math.abs(bridgedClose - open) * (0.45 + nextRand() * 0.9) + bridgedClose * stepVol * 0.45;
    const high = Math.max(open, bridgedClose) + wickSpan * (0.35 + nextRand() * 0.65);
    const low = Math.max(currentPrice * 0.05, Math.min(open, bridgedClose) - wickSpan * (0.35 + nextRand() * 0.65));
    const volume = Math.round((40 + nextRand() * 110 + (Math.abs(bridgedClose - open) / bridgedClose) * 4000) * 1000);

    points.push({
      timeLabel: formatTimeLabel(i, count, timeframe),
      open,
      high,
      low,
      close: bridgedClose,
      volume,
    });
  }

  return { points, periodChangePct: rawPeriodPct };
}

function formatTimeLabel(index: number, total: number, timeframe: Timeframe): string {
  if (timeframe === '1D') {
    const startMinutes = 9 * 60 + 30;
    const totalMinutes = 6 * 60 + 30;
    const m = startMinutes + Math.round((index / (total - 1)) * totalMinutes);
    const hh = String(Math.floor(m / 60)).padStart(2, '0');
    const mm = String(m % 60).padStart(2, '0');
    return `${hh}:${mm}`;
  }
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  const daysBackMap: Record<Exclude<Timeframe, '1D'>, number> = {
    '5D': 5,
    '1M': 30,
    '6M': 182,
    YTD: 315,
    '1Y': 365,
    '5Y': 1825,
  };
  const daysBack = daysBackMap[timeframe];
  const baseDate = new Date(2026, 10, 12);
  const offsetDays = Math.round(((total - 1 - index) / (total - 1)) * daysBack);
  const d = new Date(baseDate.getFullYear(), baseDate.getMonth(), baseDate.getDate() - offsetDays);
  if (timeframe === '5Y') {
    return `${months[d.getMonth()]} '${String(d.getFullYear()).slice(-2)}`;
  }
  return `${months[d.getMonth()]} ${d.getDate()}`;
}

